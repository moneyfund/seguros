import {before,after,test} from 'node:test';
import {readFileSync} from 'node:fs';
import {initializeTestEnvironment,assertSucceeds,assertFails} from '@firebase/rules-unit-testing';
import {doc,setDoc,updateDoc} from 'firebase/firestore';
import {ref,uploadBytes,getBytes,deleteObject,listAll,getMetadata} from 'firebase/storage';
const projectId='demo-acos-enterprise';
let env;
const root='companies/main/';
const agent='agent-a',other='agent-b',operator='operator-a',operator2='operator-b',service='service-a',finance='finance-a',limited='limited-a';
const claims=uid=>({email:uid+'@example.test',email_verified:true});
const ctx=uid=>env.authenticatedContext(uid,claims(uid));
const member=(role,allowedSections=['clientes','polizas','documentos','finanzas'])=>({role,roles:[role],active:true,allowedSections});
const jpg='front-11111111-1111-4111-8111-111111111111.jpg';
const back='back-22222222-2222-4222-8222-222222222222.jpg';
const pdf='policy-44444444-4444-4444-8444-444444444444.pdf';
const path=(name,id='request-a')=>root+'enterpriseTrial/'+id+'/'+name;
const photo=new Uint8Array([255,216,255,217]);
const policy=new TextEncoder().encode('%PDF-1.4\n%synthetic only');
const file=(uid,name,id)=>ref(ctx(uid).storage(),path(name,id));
const upload=(uid,name,bytes,contentType,id)=>uploadBytes(file(uid,name,id),bytes,{contentType});
const setRequest=(data)=>env.withSecurityRulesDisabled(async c=>updateDoc(doc(c.firestore(),root+'enterpriseIssuance/request-a'),data));
before(async()=>{
 env=await initializeTestEnvironment({projectId,firestore:{rules:readFileSync('firestore.rules','utf8')},storage:{rules:readFileSync('storage.rules','utf8')}});
 await env.clearFirestore();
 await env.clearStorage();
 await env.withSecurityRulesDisabled(async c=>{
  const db=c.firestore();
  for(const [uid,role] of [[agent,'ventas'],[other,'ventas'],[operator,'operaciones'],[operator2,'operaciones'],[service,'servicio'],[finance,'finanzas']]) await setDoc(doc(db,root+'members/'+uid),member(role));
  await setDoc(doc(db,root+'members/'+limited),member('ventas',['documentos']));
  await setDoc(doc(db,root+'enterpriseIssuance/request-a'),{agentUid:agent,operatorUid:'',status:'DRAFT',trial:true});
 });
});
after(async()=>{if(env)await env.cleanup();});
test('Storage: own attachments, authorized service readers, assigned reviewer and revocation',async()=>{
 await assertSucceeds(upload(agent,jpg,photo,'image/jpeg'));
 await assertSucceeds(getMetadata(file(agent,jpg)));
 await assertFails(getBytes(file(other,jpg)));
 await assertFails(getBytes(file(finance,jpg)));
 await assertFails(getBytes(file(limited,jpg)));
 await assertFails(getBytes(ref(env.unauthenticatedContext().storage(),path(jpg))));
 await assertSucceeds(getBytes(file(operator,jpg)));
 await assertSucceeds(getBytes(file(service,jpg)));
 await assertFails(upload(other,back,photo,'image/jpeg'));
 await assertFails(upload(agent,back,policy,'application/pdf'));
 await assertFails(upload(agent,back,new Uint8Array(8*1024*1024+1),'image/jpeg'));
 await assertFails(upload(agent,jpg,photo,'image/jpeg'));
 await assertFails(deleteObject(file(agent,jpg)));
 await assertFails(listAll(ref(ctx(agent).storage(),root+'enterpriseTrial/request-a')));
 await assertFails(upload(agent,pdf,policy,'application/pdf'));
 await assertFails(upload(operator,pdf,policy,'application/pdf'));
 await assertFails(upload(agent,jpg,photo,'image/jpeg','unknown-request'));
 await setRequest({status:'IN_REVIEW',operatorUid:operator});
 await assertFails(upload(agent,back,photo,'image/jpeg'));
 await assertFails(upload(operator2,pdf,policy,'application/pdf'));
 await assertFails(upload(service,pdf,policy,'application/pdf'));
 await assertSucceeds(upload(operator,pdf,policy,'application/pdf'));
 await setRequest({status:'ISSUED',pdf});
 await assertSucceeds(getBytes(file(agent,pdf)));
 await assertSucceeds(getBytes(file(service,pdf)));
 await assertFails(getBytes(file(other,pdf)));
 await assertFails(upload(operator,pdf,policy,'application/pdf'));
 await env.withSecurityRulesDisabled(async c=>updateDoc(doc(c.firestore(),root+'members/'+agent),{active:false}));
 await assertFails(getBytes(file(agent,jpg)));
 await assertFails(getBytes(file(agent,pdf)));
});
