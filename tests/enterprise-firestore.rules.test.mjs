import {after,before,test} from 'node:test';
import {readFileSync} from 'node:fs';
import {initializeTestEnvironment,assertSucceeds,assertFails} from '@firebase/rules-unit-testing';
import {collection,doc,getDoc,getDocs,query,setDoc,updateDoc,deleteDoc,where,serverTimestamp} from 'firebase/firestore';
let env; const projectId='demo-acos-enterprise';
const base='companies/main/';
const aUid='agent-a',bUid='agent-b',oUid='operator-a',serviceUid='service-a',financeUid='finance-a';
const claims=uid=>({email:uid+'@example.test',email_verified:true});
const ctx=uid=>env.authenticatedContext(uid,claims(uid)).firestore();
const d=(db,path)=>doc(db,base+path);
const q=(db,col,field,uid)=>query(collection(db,base+col),where(field,'==',uid));
const views=['clientes','polizas','finanzas','documentos'];
const client=(uid)=>({fullName:'CLIENTE FICTICIO '+uid,email:uid+'@example.test',phone:'',city:'Prueba',ownerUid:uid,trial:true,createdAt:serverTimestamp()});
const docs={front:'front-11111111-1111-4111-8111-111111111111.jpg',back:'back-22222222-2222-4222-8222-222222222222.jpg',registration:'registration-33333333-3333-4333-8333-333333333333.png'};
const draft=(uid,id)=>({clientId:id,clientName:'CLIENTE FICTICIO '+uid,agentUid:uid,insurerId:'iniser',productKey:'VEHICLE_MANDATORY',plate:'FICTICIA',files:{front:'',back:'',registration:''},status:'DRAFT',pdf:'',policyNumber:'',startDate:'',endDate:'',premiumCents:0,currency:'USD',operatorUid:'',reason:'',revision:0,agentSeenRevision:0,trial:true,createdAt:serverTimestamp(),updatedAt:serverTimestamp()});
before(async()=>{env=await initializeTestEnvironment({projectId,firestore:{rules:readFileSync('firestore.rules','utf8')}});await env.clearFirestore();await env.withSecurityRulesDisabled(async c=>{const db=c.firestore();await setDoc(d(db,'settings/enterpriseTrial'),{enabled:true});for(const [uid,role] of [[aUid,'ventas'],[bUid,'ventas'],[oUid,'operaciones'],[serviceUid,'servicio'],[financeUid,'finanzas']])await setDoc(d(db,'members/'+uid),{role,roles:[role],active:true,allowedSections:views});await setDoc(d(db,'commissions/a'),{agentUid:aUid,amountCents:1000});await setDoc(d(db,'commissions/b'),{agentUid:bUid,amountCents:2000});await setDoc(d(db,'policies/a'),{assignedToUid:aUid});await setDoc(d(db,'policies/b'),{assignedToUid:bUid});});});
after(async()=>{if(env)await env.cleanup();});
test('Expediente y emisión: aislamiento, permisos, transiciones y revisión',async()=>{
 const a=ctx(aUid),b=ctx(bUid),o=ctx(oUid),s=ctx(serviceUid),f=ctx(financeUid),anon=env.unauthenticatedContext().firestore();
 const profile={documentType:'CEDULA',documentNumber:'TEST-001',birthDate:'2000-01-01',nationality:'Ficticia',occupation:'Prueba',department:'Prueba',address:'Dirección de ejemplo',alternatePhone:''};
 await assertSucceeds(setDoc(d(a,'enterpriseClients/a'),{...client(aUid),profile}));
 await assertFails(setDoc(d(a,'enterpriseClients/invalid-profile'),{...client(aUid),profile:{...profile,unexpected:'no'}}));
 await assertSucceeds(setDoc(d(b,'enterpriseClients/b'),client(bUid)));
 await assertFails(setDoc(d(a,'enterpriseClients/forged'),client(bUid)));
 await assertFails(getDoc(d(a,'enterpriseClients/b')));
 await assertFails(getDoc(d(anon,'enterpriseClients/a')));
 await assertFails(getDocs(collection(a,base+'enterpriseClients')));
 await assertSucceeds(getDocs(q(a,'enterpriseClients','ownerUid',aUid)));
 await assertSucceeds(getDocs(collection(o,base+'enterpriseClients')));
 await assertSucceeds(getDocs(collection(s,base+'enterpriseClients')));
 await assertFails(getDoc(d(f,'enterpriseClients/a')));
 await assertFails(updateDoc(d(a,'enterpriseClients/a'),{ownerUid:bUid}));
 await assertFails(setDoc(d(b,'enterpriseIssuance/forged'),draft(bUid,'a')));
 const vehicle={make:'Prueba',model:'Modelo',year:'2020',color:'Azul',vin:'TEST-CHASIS',use:'Particular'};
 await assertSucceeds(setDoc(d(a,'enterpriseIssuance/a'),{...draft(aUid,'a'),vehicle}));
 await assertFails(setDoc(d(a,'enterpriseIssuance/invalid-vehicle'),{...draft(aUid,'a'),vehicle:{...vehicle,year:'texto'}}));
 await assertFails(getDoc(d(b,'enterpriseIssuance/a')));
 await assertFails(getDocs(collection(a,base+'enterpriseIssuance')));
 await assertSucceeds(getDocs(q(a,'enterpriseIssuance','agentUid',aUid)));
 await assertFails(updateDoc(d(a,'enterpriseIssuance/a'),{status:'SUBMITTED',revision:1,updatedAt:serverTimestamp()}));
 await assertSucceeds(updateDoc(d(a,'enterpriseIssuance/a'),{files:docs,updatedAt:serverTimestamp()}));
 await assertSucceeds(updateDoc(d(a,'enterpriseIssuance/a'),{status:'SUBMITTED',operatorUid:'',reason:'',revision:1,updatedAt:serverTimestamp()}));
 await assertFails(updateDoc(d(a,'enterpriseIssuance/a'),{status:'IN_REVIEW',operatorUid:aUid,revision:2,updatedAt:serverTimestamp()}));
 await assertFails(updateDoc(d(s,'enterpriseIssuance/a'),{status:'IN_REVIEW',operatorUid:serviceUid,revision:2,updatedAt:serverTimestamp()}));
 await assertSucceeds(updateDoc(d(o,'enterpriseIssuance/a'),{status:'IN_REVIEW',operatorUid:oUid,revision:2,updatedAt:serverTimestamp()}));
 await assertSucceeds(updateDoc(d(o,'enterpriseIssuance/a'),{status:'NEEDS_CORRECTION',reason:'Foto ficticia borrosa',revision:3,updatedAt:serverTimestamp()}));
 await assertSucceeds(updateDoc(d(a,'enterpriseIssuance/a'),{agentSeenRevision:3}));
 await assertFails(updateDoc(d(b,'enterpriseIssuance/a'),{agentSeenRevision:3}));
 await assertSucceeds(updateDoc(d(a,'enterpriseIssuance/a'),{status:'SUBMITTED',operatorUid:'',reason:'',revision:4,updatedAt:serverTimestamp()}));
 await assertSucceeds(updateDoc(d(o,'enterpriseIssuance/a'),{status:'IN_REVIEW',operatorUid:oUid,revision:5,updatedAt:serverTimestamp()}));
 await assertFails(updateDoc(d(o,'enterpriseIssuance/a'),{status:'ISSUED',revision:6,updatedAt:serverTimestamp()}));
 const result={status:'ISSUED',pdf:'policy-44444444-4444-4444-8444-444444444444.pdf',policyNumber:'TEST-01',startDate:'2026-11-01',endDate:'2027-11-01',premiumCents:1000,currency:'USD',revision:6,updatedAt:serverTimestamp()};
 await assertSucceeds(updateDoc(d(o,'enterpriseIssuance/a'),result));
 await assertSucceeds(getDoc(d(a,'enterpriseIssuance/a')));
 await assertFails(updateDoc(d(a,'enterpriseIssuance/a'),{agentUid:bUid}));
 await assertFails(getDoc(d(a,'policies/b')));
 await assertSucceeds(getDocs(q(a,'policies','assignedToUid',aUid)));
 await assertFails(getDoc(d(a,'commissions/b')));
 await assertSucceeds(getDocs(q(a,'commissions','agentUid',aUid)));
 await assertSucceeds(getDocs(collection(f,base+'commissions')));
 await assertFails(updateDoc(d(a,'commissions/a'),{paidCents:1000}));
 await env.withSecurityRulesDisabled(async c=>{await updateDoc(d(c.firestore(),'settings/enterpriseTrial'),{enabled:false});});
 await assertFails(getDoc(d(a,'enterpriseClients/a')));
 await assertFails(getDoc(d(o,'enterpriseIssuance/a')));
});

test('Laboratorio: no se permite borrar registros sin ser propietario verificado',async()=>{
 await env.withSecurityRulesDisabled(async c=>setDoc(d(c.firestore(),'pilotClients/fixture'),{isPilot:true}));
 const anon=env.unauthenticatedContext().firestore();
 await assertFails(deleteDoc(d(anon,'pilotClients/fixture')));
 await assertFails(deleteDoc(d(ctx(aUid),'pilotClients/fixture')));
 const owner=env.authenticatedContext('owner-test',{email:'amyblandon171@gmail.com',email_verified:true}).firestore();
 await assertSucceeds(deleteDoc(d(owner,'pilotClients/fixture')));
});
