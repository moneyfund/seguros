import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {readFile,mkdir} from 'node:fs/promises';
import {resolve,extname,sep} from 'node:path';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.ACOS_QA_MODULES?resolve(process.env.ACOS_QA_MODULES,'playwright'):'playwright');
const dist=resolve('dist'),output=resolve('public-site-qa');
await mkdir(output,{recursive:true});
const mime={'.html':'text/html','.js':'text/javascript','.css':'text/css','.svg':'image/svg+xml','.webp':'image/webp','.png':'image/png','.ttf':'font/ttf','.woff2':'font/woff2'};
const server=createServer(async(req,res)=>{try{const f=resolve(dist,'.'+new URL(req.url,'http://localhost').pathname.replace(/\/$/,'/index.html'));if(!f.startsWith(dist+sep)){res.writeHead(403).end();return;}res.writeHead(200,{'Content-Type':mime[extname(f)]||'application/octet-stream'}).end(await readFile(f));}catch{res.writeHead(404).end();}});
await new Promise(done=>server.listen(4174,'127.0.0.1',done));
let browser;
try{
 browser=await chromium.launch({headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 const page=await context.newPage(),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 await page.goto('http://127.0.0.1:4174/#/inicio');
 await page.locator('.ap-carousel-track').waitFor();
 await page.locator('#acos-public-loader').waitFor({state:'hidden'});
 const track=page.locator('.ap-carousel-track');
 assert.equal(await track.locator('.ap-product').count(),7);
 const verifyCards=async locator=>{
  const geometry=await locator.evaluateAll(nodes=>nodes.map(card=>{const r=card.getBoundingClientRect(),m=card.querySelector('.ap-product-media').getBoundingClientRect(),b=card.querySelector('.ap-product-body').getBoundingClientRect();return {w:r.width,h:r.height,vertical:m.bottom<=b.top+1,fullWidth:Math.abs(m.width-b.width)<2};}));
  assert.ok(geometry.every(c=>c.vertical&&c.fullWidth),'Every photo must be on top and full width');
  assert.ok(geometry.every(c=>Math.abs(c.w-geometry[0].w)<2&&Math.abs(c.h-geometry[0].h)<2),'All desktop cards must have equal dimensions');
 };
 await verifyCards(track.locator('.ap-product'));
 assert.ok(await track.evaluate(el=>el.scrollWidth>el.clientWidth));
 await page.getByRole('button',{name:'Siguiente seguro',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.ap-carousel-track').scrollLeft>0);
 await page.getByRole('button',{name:'Seguro anterior',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('.ap-carousel-track').scrollLeft<3);
 await page.getByRole('button',{name:'Pausar carrusel',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'Reanudar carrusel',exact:true}).count(),1);
 await page.getByRole('button',{name:'Empresas',exact:true}).click();
 assert.equal(await track.locator('.ap-product').count(),13);
 await verifyCards(track.locator('.ap-product'));
 await page.locator('.ap-carousel-track').scrollIntoViewIfNeeded();
 await page.screenshot({path:resolve(output,'carousel-desktop.png')});
 await page.locator('.ap-nav').getByRole('link',{name:'Nuestros seguros',exact:true}).click();
 await page.locator('.ap-catalog-page').waitFor();
 assert.equal(new URL(page.url()).hash,'#/seguros');
 assert.equal(await page.locator('.ap-carousel-track').count(),0);
 assert.equal(await page.locator('#catalogo-personas .ap-product').count(),7);
 assert.equal(await page.locator('#catalogo-empresas .ap-product').count(),13);
 await verifyCards(page.locator('#catalogo-personas .ap-product'));
 await verifyCards(page.locator('#catalogo-empresas .ap-product'));
 const personalPhotos=await page.locator('#catalogo-personas .ap-product-media img').evaluateAll(imgs=>imgs.map(img=>img.getAttribute('src')));
 const businessPhotos=await page.locator('#catalogo-empresas .ap-product-media img').evaluateAll(imgs=>imgs.map(img=>img.getAttribute('src')));
 assert.equal(new Set([...personalPhotos,...businessPhotos]).size,19);
 await page.locator('#catalogo-empresas .ap-product-agricola button').click();
 await page.locator('dialog[open]').waitFor();
 assert.match(await page.locator('dialog h2').innerText(),/agrícola/);
 await page.locator('dialog').getByRole('button',{name:'Solicitar asesoría'}).click();
 assert.equal(await page.locator('#ap-interest').inputValue(),'agricola');
 await page.keyboard.press('Escape');
 await page.locator('#catalogo-empresas').scrollIntoViewIfNeeded();
 await page.screenshot({path:resolve(output,'catalog-desktop.png')});
 await page.reload();
 await page.locator('.ap-catalog-page').waitFor();
 await page.locator('#acos-public-loader').waitFor({state:'hidden'});
 for(const width of [1024,768,390,320]){
  await page.setViewportSize({width,height:850});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'Catalog overflow at '+width);
  assert.deepEqual(await page.locator('.ap-catalog-grid .ap-product').evaluateAll(nodes=>nodes.filter(el=>{const r=el.getBoundingClientRect();return r.width>0&&(r.left<-1||r.right>innerWidth+1)}).map(el=>el.textContent)),[]);
 }
 await page.locator('.ap-catalog-breadcrumb').click();
 await page.locator('.ap-carousel-track').waitFor();
 assert.equal(await page.locator('.ap-catalog-page').count(),0);
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 await page.locator('.ap-carousel-track').scrollIntoViewIfNeeded();
 await page.screenshot({path:resolve(output,'carousel-mobile.png')});
 await page.route('https://images.pexels.com/photos/**',route=>route.abort());
 await page.goto('http://127.0.0.1:4174/#/seguros');
 await page.locator('#catalogo-personas .ap-product-soa').scrollIntoViewIfNeeded();
 await page.waitForFunction(()=>{const img=document.querySelector('#catalogo-personas .ap-product-soa img');return img?.getAttribute('src')==='/images/vehiculos.webp'&&img.complete&&img.naturalWidth>0;});
 assert.deepEqual(errors,[]);
 console.log('PASS catalog: uniform vertical cards, manual carousel controls, independent route, exact 7/13 listings, responsive widths and CDN fallback');
}finally{await browser?.close();await new Promise(done=>server.close(done));}
